-- AdventureWorks: export six Gold tables from Snowflake to S3 curated/
-- Exports are written as single CSV files with headers.

--Exporting Gold tables
CREATE STAGE IF NOT EXISTS
    ADVENTUREWORKS_DB.PUBLIC.ADVENTUREWORKS_CURATED_STAGE

URL = 's3://adventureworks-snowflake-2026/curated/'
STORAGE_INTEGRATION = ADVENTUREWORKS_S3_INT;


LIST @ADVENTUREWORKS_DB.PUBLIC.ADVENTUREWORKS_CURATED_STAGE;

CREATE OR REPLACE FILE FORMAT
    ADVENTUREWORKS_DB.PUBLIC.AW_EXPORT_FORMAT

TYPE = CSV
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
COMPRESSION = NONE
NULL_IF = ('NULL');


COPY INTO
    @ADVENTUREWORKS_DB.PUBLIC.ADVENTUREWORKS_CURATED_STAGE/DIM_DATE.csv

FROM (
    SELECT *
    FROM ADVENTUREWORKS_DB.ANALYTICS.DIM_DATE
)

FILE_FORMAT = (
    FORMAT_NAME = 'ADVENTUREWORKS_DB.PUBLIC.AW_EXPORT_FORMAT'
)

HEADER = TRUE
SINGLE = TRUE
OVERWRITE = TRUE;

LIST @ADVENTUREWORKS_DB.PUBLIC.ADVENTUREWORKS_CURATED_STAGE;


