    COUNT(DISTINCT "SalesOrderDetailID") AS UNIQUE_DETAIL_IDS,

    COUNT_IF("SalesOrderDetailID" IS NULL) AS NULL_DETAIL_IDS,

    COUNT_IF(
        "OrderQty" <= 0
        OR "UnitPrice" < 0
        OR "UnitPriceDiscount" < 0
        OR "UnitPriceDiscount" > 1
    ) AS INVALID_VALUES,

    COUNT_IF(
        ABS(
            "LineTotal" -
            ("OrderQty" * "UnitPrice" * (1 - "UnitPriceDiscount"))
        ) > 0.01
    ) AS INVALID_LINE_TOTALS,

    COUNT_IF(
        "SalesOrderID" IS NULL
    ) AS NULL_ORDER_IDS

FROM ADVENTUREWORKS_DB.RAW.SALESORDERDETAIL;


