-- AdventureWorks: initial RAW ingestion
-- Loads the two SalesOrder tables used for the first ingestion test.
-- The subsequent generated ingestion script loads the remaining 33 tables.

CREATE TABLE SALESORDERHEADER
USING TEMPLATE (
    SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*))
    FROM TABLE(
        INFER_SCHEMA(
            LOCATION => '@ADVENTUREWORKS_S3_STAGE/Sales/adventureworks.Sales.SalesOrderHeader.csv',
            FILE_FORMAT => 'AW_CSV_FORMAT'
        )
    )
);

COPY INTO SALESORDERHEADER
FROM @ADVENTUREWORKS_S3_STAGE/Sales/
FILES = ('adventureworks.Sales.SalesOrderHeader.csv')
FILE_FORMAT = (FORMAT_NAME = AW_CSV_FORMAT)
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

SELECT COUNT(*) AS TOTAL_ROWS
FROM SALESORDERHEADER;
SELECT *
FROM SALESORDERHEADER
LIMIT 10;


CREATE TABLE SALESORDERDETAIL
USING TEMPLATE (
    SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*))
    FROM TABLE(
        INFER_SCHEMA(
            LOCATION => '@ADVENTUREWORKS_S3_STAGE/Sales/adventureworks.Sales.SalesOrderDetail.csv',
            FILE_FORMAT => 'AW_CSV_FORMAT'
        )
    )
);

COPY INTO SALESORDERDETAIL
FROM @ADVENTUREWORKS_S3_STAGE/Sales/
FILES = ('adventureworks.Sales.SalesOrderDetail.csv')
FILE_FORMAT = (FORMAT_NAME = AW_CSV_FORMAT)
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

SELECT COUNT(*) FROM SALESORDERDETAIL;

LIST @ADVENTUREWORKS_S3_STAGE;


USE DATABASE ADVENTUREWORKS_DB;

SHOW TABLES IN SCHEMA RAW;

SHOW TABLES IN DATABASE ADVENTUREWORKS_DB;

ALTER TABLE ADVENTUREWORKS_DB.PUBLIC.SALESORDERHEADER
RENAME TO ADVENTUREWORKS_DB.RAW.SALESORDERHEADER;

ALTER TABLE ADVENTUREWORKS_DB.PUBLIC.SALESORDERDETAIL
RENAME TO ADVENTUREWORKS_DB.RAW.SALESORDERDETAIL;
