-- from the original script are retained alongside the transformations.

CREATE OR REPLACE TABLE ADVENTUREWORKS_DB.CLEAN.SALESORDERHEADER AS

SELECT * REPLACE (
    ROUND("SubTotal", 2)::NUMBER(18,2) AS "SubTotal",
    ROUND("TaxAmt", 2)::NUMBER(18,2) AS "TaxAmt",
    ROUND("Freight", 2)::NUMBER(18,2) AS "Freight",
    ROUND("TotalDue", 2)::NUMBER(18,2) AS "TotalDue"
)

FROM ADVENTUREWORKS_DB.RAW.SALESORDERHEADER;

SELECT *
FROM ADVENTUREWORKS_DB.CLEAN.SALESORDERHEADER
LIMIT 10;



DESCRIBE TABLE ADVENTUREWORKS_DB.RAW.SALESORDERDETAIL;

SELECT *
FROM ADVENTUREWORKS_DB.RAW.SALESORDERDETAIL
LIMIT 20;

SELECT
    COUNT(*) AS TOTAL_ROWS,

    COUNT(DISTINCT "SalesOrderDetailID") AS UNIQUE_DETAIL_IDS,

    COUNT_IF("SalesOrderDetailID" IS NULL) AS NULL_DETAIL_IDS,

    COUNT_IF(
        "OrderQty" <= 0
        OR "UnitPrice" < 0
        OR "UnitPriceDiscount" < 0
        OR "UnitPriceDiscount" > 1
    ) AS INVALID_VALUES,

    COUNT_IF(
        ABS(
            "LineTotal" -
            ("OrderQty" * "UnitPrice" * (1 - "UnitPriceDiscount"))
        ) > 0.01
    ) AS INVALID_LINE_TOTALS,

    COUNT_IF(
        "SalesOrderID" IS NULL
    ) AS NULL_ORDER_IDS

FROM ADVENTUREWORKS_DB.RAW.SALESORDERDETAIL;


SELECT COUNT(*) AS ORPHAN_ORDER_IDS
FROM ADVENTUREWORKS_DB.RAW.SALESORDERDETAIL D
LEFT JOIN ADVENTUREWORKS_DB.RAW.SALESORDERHEADER H
    ON D."SalesOrderID" = H."SalesOrderID"
WHERE H."SalesOrderID" IS NULL;

